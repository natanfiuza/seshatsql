<script setup lang="ts">
import { computed, onBeforeUnmount, ref } from 'vue'
import { useI18n } from 'vue-i18n'

import { createDebounceScheduler } from '../../../application/persistence/debounce-scheduler'
import {
  PERSISTENCE_SCHEMA_VERSION,
  type PersistedCursor,
  type PersistedSelection,
  type PersistedTab,
  type PersistenceWarning,
  type SaveFailureReason,
  type SaveResult,
  type StartupState,
  type TabsStateV1
} from '../../../domain/persistence/types'
import type { CopyOutcome } from '../grid/copy'
import { setLocale, type SupportedLocale } from '../i18n'
import type { ThemePreference } from '../theme/theme'
import { createThemeController } from '../theme/useTheme'
import LabEditorPane from './lab/LabEditorPane.vue'
import LabObjectTree from './lab/LabObjectTree.vue'
import LabResultsPane from './lab/LabResultsPane.vue'
import LabSqlLog from './lab/LabSqlLog.vue'
import { SAMPLE_ROWS, SAMPLE_SQL } from './lab/sample-data'
import PersistenceBanner from './persistence/PersistenceBanner.vue'
import AppMenuBar from './shell/AppMenuBar.vue'
import AppSplit from './shell/AppSplit.vue'
import AppStatusBar from './shell/AppStatusBar.vue'
import AppToolbar from './shell/AppToolbar.vue'

// Provisional main screen: the real workspace replaces it in T07/T09.
const COPY_NOTICE_MS = 2500
const TABS_DEBOUNCE_MS = 500
const DEFAULT_TAB_ID = 'query-1'

const props = defineProps<{
  startup: StartupState
}>()

const { t } = useI18n()

const locale = ref<SupportedLocale>(props.startup.preferences.locale)
const theme = createThemeController({
  initialPreference: props.startup.preferences.theme,
  onChange: () => {
    void persistPreferences()
  }
})

const tabs = ref<PersistedTab[]>(restoreTabs(props.startup.tabs, t('shell.tabs.queryOne')))
const activeId = ref<string>(resolveActiveId(props.startup.tabs, tabs.value))

const startupWarnings = ref<PersistenceWarning[]>([...props.startup.warnings])
const tabSaveWarning = ref<PersistenceWarning | null>(null)
const preferencesSaveWarning = ref<PersistenceWarning | null>(null)
const closeFailure = ref(false)

const scheduler = createDebounceScheduler(TABS_DEBOUNCE_MS)
let dirty = false
let pendingSave = false
let saveChain: Promise<boolean> = Promise.resolve(true)
let copyTimer: ReturnType<typeof setTimeout> | null = null

const activeTab = computed<PersistedTab | null>(
  () => tabs.value.find((tab) => tab.id === activeId.value) ?? tabs.value[0] ?? null
)
const activeSql = computed(() => activeTab.value?.text ?? '')
const activeCursor = computed(() => activeTab.value?.cursor ?? null)
const activeSelection = computed(() => activeTab.value?.selection ?? null)

const editorTabs = computed(() =>
  tabs.value.map((tab, index) => ({
    id: tab.id,
    // The first tab is generated by the application, so its label follows the
    // interface language. Additional restored tabs keep their stored title.
    label: index === 0 ? t('shell.tabs.queryOne') : tab.title
  }))
)

const bannerWarnings = computed<PersistenceWarning[]>(() => {
  const warnings = [...startupWarnings.value]
  if (tabSaveWarning.value !== null) {
    warnings.push(tabSaveWarning.value)
  }
  if (preferencesSaveWarning.value !== null) {
    warnings.push(preferencesSaveWarning.value)
  }
  return warnings
})
const canRetry = computed(
  () => tabSaveWarning.value !== null || preferencesSaveWarning.value !== null || closeFailure.value
)
const dismissible = computed(() => startupWarnings.value.length > 0)

const copyStatus = ref<'success' | 'failure' | null>(null)

const statusDetail = computed(() => {
  if (copyStatus.value === 'success') {
    return t('shell.copy.success')
  }
  if (copyStatus.value === 'failure') {
    return t('shell.copy.failure')
  }
  return t('shell.status.rows', { count: SAMPLE_ROWS.length })
})

if (
  props.startup.tabs.tabs.length === 0 ||
  props.startup.tabs.activeTabId !== activeId.value
) {
  scheduleTabsSave()
}

const unsubscribeCloseRequested = window.seshat.app.onCloseRequested(() => {
  void handleCloseRequested()
})
const unsubscribeCloseFailed = window.seshat.app.onCloseFailed(() => {
  closeFailure.value = true
})

onBeforeUnmount(() => {
  scheduler.cancel()
  unsubscribeCloseRequested()
  unsubscribeCloseFailed()
  theme.dispose()
  if (copyTimer !== null) {
    clearTimeout(copyTimer)
    copyTimer = null
  }
})

function restoreTabs(state: TabsStateV1, defaultTitle: string): PersistedTab[] {
  const restored = [...state.tabs].sort((left, right) => left.order - right.order)
  if (restored.length > 0) {
    return restored
  }
  return [
    {
      id: DEFAULT_TAB_ID,
      title: defaultTitle,
      text: SAMPLE_SQL,
      connectionId: null,
      database: null,
      order: 0,
      cursor: null,
      selection: null
    }
  ]
}

function resolveActiveId(state: TabsStateV1, restored: readonly PersistedTab[]): string {
  if (state.activeTabId !== null && restored.some((tab) => tab.id === state.activeTabId)) {
    return state.activeTabId
  }
  return restored[0]?.id ?? DEFAULT_TAB_ID
}

function tabState(): TabsStateV1 {
  return {
    schemaVersion: PERSISTENCE_SCHEMA_VERSION,
    activeTabId: activeId.value,
    // Deep plain copies: Electron's structured clone rejects Vue's reactive
    // proxies, so the IPC payload never carries refs/proxies.
    tabs: tabs.value.map((tab) => ({
      ...tab,
      cursor: tab.cursor === null ? null : { ...tab.cursor },
      selection: tab.selection === null ? null : { ...tab.selection }
    }))
  }
}

function saveFailureWarning(reason: SaveFailureReason): PersistenceWarning {
  const paths = props.startup.dataDirectory === '' ? [] : [props.startup.dataDirectory]
  if (reason === 'readonly-newer') {
    return { code: 'future-version', paths }
  }
  if (reason === 'file-too-large') {
    return { code: 'file-too-large', paths }
  }
  return { code: 'save-failed', paths }
}

function markDirty(): void {
  dirty = true
}

function scheduleTabsSave(): void {
  markDirty()
  pendingSave = true
  scheduler.schedule(() => {
    pendingSave = false
    void saveTabs()
  })
}

function saveTabs(): Promise<boolean> {
  const attempt = async (): Promise<boolean> => {
    if (!dirty) {
      return true
    }
    let result: SaveResult
    try {
      result = await window.seshat.tabs.save(tabState())
    } catch {
      // A rejected invoke (for example an uncloneable payload) must surface as
      // a save failure, not poison the chain for every later attempt.
      tabSaveWarning.value = saveFailureWarning('io-error')
      return false
    }
    if (result.ok) {
      dirty = false
      tabSaveWarning.value = null
      return true
    }
    tabSaveWarning.value = saveFailureWarning(result.reason)
    return false
  }
  // Both handlers run the attempt so a previously rejected link cannot wedge
  // the queue.
  saveChain = saveChain.then(attempt, attempt)
  return saveChain
}

/** Writes pending edits immediately. Returns whether the stored state is current. */
async function flushTabs(): Promise<boolean> {
  if (pendingSave) {
    pendingSave = false
    scheduler.cancel()
  }
  if (dirty) {
    return saveTabs()
  }
  await saveChain
  return !dirty
}

async function persistPreferences(): Promise<void> {
  try {
    const result = await window.seshat.preferences.set({
      theme: theme.preference.value,
      locale: locale.value
    })
    preferencesSaveWarning.value = result.ok ? null : saveFailureWarning(result.reason)
  } catch {
    preferencesSaveWarning.value = saveFailureWarning('io-error')
  }
}

function updateActive(
  patch: Partial<Pick<PersistedTab, 'text' | 'cursor' | 'selection'>>
): void {
  const id = activeId.value
  tabs.value = tabs.value.map((tab) => (tab.id === id ? { ...tab, ...patch } : tab))
}

function onThemeChange(value: ThemePreference): void {
  theme.setPreference(value)
}

function onLocaleChange(value: SupportedLocale): void {
  locale.value = value
  setLocale(value)
  void persistPreferences()
}

function onTextChange(value: string): void {
  updateActive({ text: value })
  scheduleTabsSave()
}

function onView(cursor: PersistedCursor, selection: PersistedSelection | null): void {
  updateActive({ cursor, selection })
  scheduleTabsSave()
}

async function onSelectTab(id: string): Promise<void> {
  if (id === activeId.value) {
    return
  }
  await flushTabs()
  activeId.value = id
  markDirty()
  await saveTabs()
}

async function handleCloseRequested(): Promise<void> {
  const saved = await flushTabs()
  if (saved) {
    window.seshat.app.replyClose({ ok: true })
    return
  }
  closeFailure.value = true
  window.seshat.app.replyClose({ ok: false })
}

async function onRetry(): Promise<void> {
  if (preferencesSaveWarning.value !== null) {
    await persistPreferences()
  }
  const saved = await flushTabs()
  if (!saved) {
    return
  }
  if (closeFailure.value) {
    closeFailure.value = false
    window.seshat.app.replyClose({ ok: true })
  }
}

function onDiscard(): void {
  closeFailure.value = false
  window.seshat.app.replyClose({ ok: true, discard: true })
}

function onDismiss(): void {
  startupWarnings.value = []
}

function onCopy(outcome: CopyOutcome): void {
  if (copyTimer !== null) {
    clearTimeout(copyTimer)
    copyTimer = null
  }
  if (outcome.copied) {
    copyStatus.value = 'success'
  } else if (outcome.reason === 'clipboard-error') {
    copyStatus.value = 'failure'
  } else {
    copyStatus.value = null
    return
  }
  // The notice replaces the row count only briefly, then the normal status returns.
  copyTimer = setTimeout(() => {
    copyStatus.value = null
    copyTimer = null
  }, COPY_NOTICE_MS)
}
</script>

<template>
  <main class="lab">
    <h1 class="sr-only">
      {{ t('app.name') }}
    </h1>

    <AppMenuBar />

    <AppToolbar
      :theme="theme.preference.value"
      :locale="locale"
      @update:theme="onThemeChange"
      @update:locale="onLocaleChange"
    />

    <PersistenceBanner
      :warnings="bannerWarnings"
      :close-failure="closeFailure"
      :can-retry="canRetry"
      :dismissible="dismissible"
      @retry="onRetry"
      @discard="onDiscard"
      @dismiss="onDismiss"
    />

    <div class="lab__body">
      <AppSplit
        direction="vertical"
        :size="270"
        :min-start="180"
        :min-end="420"
        :label="t('shell.split.tree')"
      >
        <template #start>
          <LabObjectTree />
        </template>

        <template #end>
          <AppSplit
            direction="horizontal"
            :size="100"
            :min-start="40"
            :min-end="180"
            :label="t('shell.split.editor')"
          >
            <template #start>
              <LabEditorPane
                :tabs="editorTabs"
                :active-id="activeId"
                :sql="activeSql"
                :theme="theme.resolved.value"
                :locale="locale"
                :cursor="activeCursor"
                :selection="activeSelection"
                @change="onTextChange"
                @select="onSelectTab"
                @view="onView"
              />
            </template>

            <template #end>
              <AppSplit
                direction="horizontal"
                pane="end"
                :size="80"
                :min-start="120"
                :min-end="40"
                :label="t('shell.split.log')"
              >
                <template #start>
                  <LabResultsPane
                    :theme="theme.resolved.value"
                    :locale="locale"
                    @copy="onCopy"
                  />
                </template>

                <template #end>
                  <LabSqlLog />
                </template>
              </AppSplit>
            </template>
          </AppSplit>
        </template>
      </AppSplit>
    </div>

    <AppStatusBar :detail="statusDetail" />
  </main>
</template>

